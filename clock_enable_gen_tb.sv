`timescale 1ns/1ps

module clock_enable_gen_tb;

    // ============================================================
    // CLOCK + RESET
    // ============================================================

    logic clk;
    logic rst_n;

    logic tick;

    // ============================================================
    // DUT
    // ============================================================

    clock_enable_gen #(

        .CLK_FREQ_HZ (100),
        .TICK_FREQ_HZ(10)

    ) dut (

        .clk  (clk),
        .rst_n(rst_n),
        .tick (tick)

    );

    // ============================================================
    // 100 MHz STYLE CLOCK
    // (10ns period)
    // ============================================================

    initial begin
        clk = 0;

        forever #5 clk = ~clk;
    end

    // ============================================================
    // RESET SEQUENCE
    // ============================================================

    initial begin

        rst_n = 0;

        #20;

        rst_n = 1;

    end

    // ============================================================
    // SIMULATION CONTROL
    // ============================================================

    initial begin

        #500;

        $finish;

    end

endmodule
